float bytes_rate_etaoin_shrdlu(bytes_t* input) {
    if (!input || !input->data || !input->length)
        return 0;

    float rating = 0;

    for (int i = 0; i < input->length; i++) {
        unsigned char c = input->data[i];
        float char_rate = ratings_EN[c];
        rating += char_rate;
    }

    return rating;
}

unsigned int hamming_distance(bytes_t* first, bytes_t* second) {
    if (!first || !second)
        return 0;
    if (!first->data || !second->data)
        return 0;
    if (!first->length || !second->length)
        return 0;
    if (first->length != second->length)
        return 0;

    int distance = 0;
    for (int i = 0; i < first->length; i++) {
        unsigned char xor = first->data[i] ^ second->data[i];
        while (xor) {
            distance += xor & 0x1;
            xor >>= 1;
        }
    }

    return distance;
}

